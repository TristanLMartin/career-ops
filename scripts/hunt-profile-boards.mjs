#!/usr/bin/env node
// hunt-profile-boards: give another profile on this machine the same company boards the default
// profile's scanners use, with that profile's own title/location filters and search terms.
//
// Reads, never writes: the default profile's portals.yml tracked_companies and its
// data/discovery-{boards,targets,vc}.yml (watchlist, discovered boards, named targets, VC
// portfolio boards). Writes only the profile's portals.yml, and only the part below the
// "generated" marker line; the filters above it are the profile's own.
//
// The profile's config/shared-boards.yml adapts the list to the person:
//   queries: [...]         replace the default profile's search terms on Amazon / Google / Apple
//                          careers (default: the profile's person.yml target_roles)
//   builtin: [...]         Built In entries that replace the default profile's ones
//   exclude: [names]       companies to leave out
//   extra_companies: [...] the profile's own portals.yml entries, added first
// Per-company title_allow (the default profile's favorites) and websearch-only entries are
// dropped, and discovery-only location strictness is not carried over.
//
// Usage: CAREER_OPS_ROOT=profiles/<id> node scripts/hunt-profile-boards.mjs [--dry-run]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isMainModule } from "../lib/is-main-module.mjs";
import { loadYaml } from "../lib/yaml-document.mjs";
import { profileDir, readPerson } from "../lib/profile-paths.mjs";
import { exitOnHelp } from "../lib/cli-guard.mjs";

const CODE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const MARKER = "# ---- generated by scripts/hunt-profile-boards.mjs: do not edit below this line ----";
export const SOURCES = ["portals.yml", "data/discovery-boards.yml", "data/discovery-targets.yml", "data/discovery-vc.yml"];

function readYaml(file) {
  try { return loadYaml(fs.readFileSync(file, "utf8").replace(/^#.*\n/gm, "")) ?? {}; } catch { return {}; }
}

/** A stable identity for one board entry, so the same board from two lists is kept once. */
export function boardKey(e) {
  const q = e.amazon ? JSON.stringify(e.amazon) : e.google ? JSON.stringify(e.google) : e.apple ? JSON.stringify(e.apple) : "";
  return `${e.provider ?? ""}|${String(e.careers_url ?? e.api ?? e.name ?? "").toLowerCase().replace(/\/+$/, "")}|${q}`;
}

/** One of the default profile's entries, adapted to the profile (or null to leave it out). */
export function adaptEntry(entry, { queries = [] } = {}) {
  if (!entry || !entry.name || entry.enabled === false) return null;
  if (entry.scan_method === "websearch") return null; // the default profile's own web searches
  const e = { ...entry };
  delete e.title_allow;
  delete e.scan_query;
  delete e.notes;
  const qs = [].concat(queries ?? []).filter(Boolean);
  if (e.provider === "builtin") return null; // replaced by the profile's own Built In searches
  if (e.provider === "amazon" && e.amazon) {
    if (!qs.length) return e;
    const { category, base_query, ...rest } = e.amazon; // drop the job-category facet + query
    return qs.map((q) => ({ ...e, amazon: { ...rest, base_query: q }, max_pages: Math.min(e.max_pages ?? 3, 3) }));
  }
  if (e.provider === "google" && e.google && qs.length) return { ...e, google: { ...e.google, queries: qs } };
  if (e.provider === "apple" && e.apple && qs.length) return { ...e, apple: { ...e.apple, queries: qs } };
  return e;
}

/** The profile's board list: its extras, then the default profile's lists adapted and deduped. */
export function profileBoards({ mainRoot = CODE_ROOT, cfg = {} } = {}) {
  const exclude = new Set([].concat(cfg.exclude ?? []).map((n) => String(n).toLowerCase()));
  const out = [];
  const seen = new Set();
  const add = (e) => {
    for (const x of [].concat(e ?? [])) {
      if (!x || exclude.has(String(x.name).toLowerCase())) continue;
      const k = boardKey(x);
      if (seen.has(k)) continue;
      seen.add(k);
      out.push({ ...x, enabled: x.enabled ?? true });
    }
  };
  for (const e of cfg.extra_companies ?? []) add(e);
  for (const b of cfg.builtin ?? []) add({ ...b, provider: "builtin" });
  for (const rel of SOURCES) {
    const doc = readYaml(path.join(mainRoot, rel));
    for (const e of [...(doc.tracked_companies ?? []), ...(doc.job_boards ?? [])]) add(adaptEntry(e, cfg));
  }
  return out;
}

/** The profile's portals.yml text with everything below MARKER replaced by `boards`. */
export function renderPortals(text, boards) {
  const i = String(text).indexOf(MARKER);
  const head = (i >= 0 ? text.slice(0, i) : `${String(text).replace(/\n*$/, "\n")}\n`).replace(/\n*$/, "\n\n");
  // JSON is valid YAML, one entry per line keeps the diff readable.
  const body = boards.map((b) => `  - ${JSON.stringify(b)}`).join("\n");
  return `${head}${MARKER}\n# ${boards.length} boards. Rebuild: CAREER_OPS_ROOT=<profile> node scripts/hunt-profile-boards.mjs\ntracked_companies:\n${body}\n`;
}

export function buildProfilePortals({ dir = profileDir(), mainRoot = CODE_ROOT, dryRun = false } = {}) {
  if (path.resolve(dir) === path.resolve(mainRoot)) throw new Error("refusing to rewrite the default profile's portals.yml; set CAREER_OPS_ROOT=profiles/<id>");
  const cfg = readYaml(path.join(dir, "config", "shared-boards.yml"));
  // Search terms default to the profile's own target roles.
  if (![].concat(cfg.queries ?? []).filter(Boolean).length) cfg.queries = [].concat(readPerson(dir).target_roles ?? []).map((r) => String(r).toLowerCase()).filter(Boolean).slice(0, 6);
  const file = path.join(dir, "portals.yml");
  const boards = profileBoards({ mainRoot, cfg });
  const text = renderPortals(fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "", boards);
  if (!dryRun) { fs.writeFileSync(`${file}.tmp`, text); fs.renameSync(`${file}.tmp`, file); }
  return { file, boards: boards.length };
}

if (isMainModule(import.meta.url)) {
  if (process.argv.includes("--help") || process.argv.includes("-h")) exitOnHelp(import.meta.url);
  const r = buildProfilePortals({ dryRun: process.argv.includes("--dry-run") });
  console.log(`hunt-profile-boards: ${r.boards} boards -> ${r.file}${process.argv.includes("--dry-run") ? " (dry run)" : ""}`);
}
